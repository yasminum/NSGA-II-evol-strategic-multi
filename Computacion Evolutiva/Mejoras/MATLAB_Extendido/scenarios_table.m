%% scenarios_table.m  —  Configuración de los 4 escenarios experimentales.
% ------------------------------------------------------------------
% Define un struct anidado con la especificación de cada escenario:
%   nombre, m2f, m3f, payload, vf, coulomb, dist, noise
%
%   S1 Nominal                 | S2 +Incertidumbre
%   S3 +Incertid.+Perturbación  | S4 +Incert.+Perturb.+Ruido
%
% Las perturbaciones externas (senoidal + escalón) y el ruido de
% medición (±1 % a escala completa) siguen el protocolo del paper.
% ------------------------------------------------------------------
function S = scenarios_table()
  S.S1 = struct('nombre','Nominal',                  ...
                'm2f',1.0, 'm3f',1.0, 'payload',0.0, ...
                'vf',1.0, 'coulomb',[0 0 0],          ...
                'dist',false, 'noise',[]);
  S.S2 = struct('nombre','Incertidumbre',            ...
                'm2f',1.10, 'm3f',1.0, 'payload',0.060, ...
                'vf',1.5, 'coulomb',[0.02 0.03 0.03],   ...
                'dist',false, 'noise',[]);
  S.S3 = struct('nombre','Incertid.+Perturbacion',    ...
                'm2f',1.10, 'm3f',1.0, 'payload',0.060, ...
                'vf',1.5, 'coulomb',[0.02 0.03 0.03],   ...
                'dist',true,  'noise',[]);
  S.S4 = struct('nombre','Incert.+Perturb.+Ruido',    ...
                'm2f',1.10, 'm3f',1.0, 'payload',0.060, ...
                'vf',1.5, 'coulomb',[0.02 0.03 0.03],   ...
                'dist',true,  'noise',struct('q',0.015,'v',0.008));
end
